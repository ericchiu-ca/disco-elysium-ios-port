#!/bin/bash
# 生成 Xcode 工程：build/xcode/DiscoElysium.xcodeproj
#   - 复制 Unity iOS Trampoline 源码与静态库，并打上 tools/patch_trampoline.py 中的补丁
#   - 生成模块注册代码、空的 IL2CPP 预编译头、App 图标（取自你本机游戏的图标）
#   - 用 XcodeGen 生成单目标工程：播放器静态链接，GameAssembly 等以 framework 嵌入
# Generate the Xcode project: build/xcode/DiscoElysium.xcodeproj
#   - copy the Unity iOS Trampoline sources and static libraries, and apply the patches in tools/patch_trampoline.py
#   - generate the module registration code, empty IL2CPP precompiled headers and the app icon (taken from your local copy of the game)
#   - generate a single-target project with XcodeGen: the player is linked statically, GameAssembly and the others are embedded as frameworks
source "$(dirname "$0")/common.sh"
require_game
require_signing_config
require_ios_support
command -v xcodegen >/dev/null || die "$(m "需要 XcodeGen：brew install xcodegen" "XcodeGen is required: brew install xcodegen")"
for fw in GameAssembly AmplifyTextureNative GLStub steam_api GalaxyCSharpGlue InControlNative; do
  [[ -d "$FW_OUT/$fw.framework" ]] || die "$(m "缺少 $fw.framework，先运行 make binaries stubs" "$fw.framework is missing; run make binaries stubs first")"
done

UNITY_VER_PARTS=(${UNITY_VERSION//./ })               # 2020 3 12f1
UNITY_VER_MIN="${UNITY_VER_PARTS[2]%%[a-z]*}"          # 12

log "$(m "准备 $XCODE_OUT" "Preparing $XCODE_OUT")"
rm -rf "$XCODE_OUT"
mkdir -p "$XCODE_OUT/Unity/Libraries" "$XCODE_OUT/Generated" "$XCODE_OUT/Assets.xcassets/AppIcon.appiconset"

cp -R "$TRAMPOLINE/Classes" "$XCODE_OUT/Unity/Classes"
cp -R "$TRAMPOLINE/UnityFramework" "$XCODE_OUT/Unity/UnityFramework"
cp "$TRAMPOLINE/Libraries/baselib.a" \
   "$TRAMPOLINE/Libraries/RegisterFeatures.cpp" "$TRAMPOLINE/Libraries/RegisterFeatures.h" \
   "$XCODE_OUT/Unity/Libraries/"
python3 -I "$ROOT/tools/patch_trampoline.py" "$XCODE_OUT/Unity"

log "$(m "给播放器库打 BC 纹理补丁" "Applying the BC texture patch to the player library")"
rm -rf "$BUILD/tmp/playerlib"
python3 -I "$ROOT/tools/patch_player_lib.py" "$TRAMPOLINE/Libraries/libiPhone-lib-il2cpp.a" \
  "$XCODE_OUT/Unity/Libraries/libiPhone-lib-il2cpp.a" "$BUILD/tmp/playerlib" 2>&1 | grep -v "is not a recognized feature"

log "$(m "生成注册代码" "Generating the registration code")"
python3 -I "$ROOT/tools/gen_registration.py" "$TRAMPOLINE/Libraries/libiPhone-lib-il2cpp.a" \
  "$XCODE_OUT/Generated/UnityRegistration.cpp"
# Trampoline 的 Prefix.pch 会包含 IL2CPP 生成代码的预编译头；游戏代码已在 GameAssembly 里，这里给空文件
# The Trampoline's Prefix.pch includes the precompiled headers of the IL2CPP-generated code; the game code is already in GameAssembly, so empty files are provided here
: > "$XCODE_OUT/Generated/pch-cpp.hpp"
: > "$XCODE_OUT/Generated/pch-c.h"
# 替代 Libraries/Il2CppOptions.cpp（原文件里的空注册函数会与上面生成的冲突）
# Replaces Libraries/Il2CppOptions.cpp (the empty registration functions in the original file would conflict with the ones generated above)
cat > "$XCODE_OUT/Generated/Il2CppOptions.cpp" <<'EOF'
// 由 scripts/gen_project.sh 生成
// Generated by scripts/gen_project.sh
bool il2cpp_no_exceptions = false;
extern "C" bool Unity_il2cppNoExceptions()
{
    return il2cpp_no_exceptions;
}

typedef void (*CodegenRegistrationFunction) ();
CodegenRegistrationFunction g_CodegenRegistration;
EOF

log "$(m "生成 App 图标" "Generating the app icon")"
ICON_SRC="$GAME_CONTENTS/Resources/PlayerIcon.icns"
sips -s format png "$ICON_SRC" --out "$XCODE_OUT/Generated/icon-src.png" >/dev/null
sips -z 1024 1024 "$XCODE_OUT/Generated/icon-src.png" --out "$XCODE_OUT/Assets.xcassets/AppIcon.appiconset/icon.png" >/dev/null
rm "$XCODE_OUT/Generated/icon-src.png"
cat > "$XCODE_OUT/Assets.xcassets/Contents.json" <<'EOF'
{ "info" : { "author" : "xcode", "version" : 1 } }
EOF
cat > "$XCODE_OUT/Assets.xcassets/AppIcon.appiconset/Contents.json" <<'EOF'
{
  "images" : [ { "filename" : "icon.png", "idiom" : "universal", "platform" : "ios", "size" : "1024x1024" } ],
  "info" : { "author" : "xcode", "version" : 1 }
}
EOF

log "$(m "写 project.yml" "Writing project.yml")"
cat > "$XCODE_OUT/project.yml" <<EOF
name: DiscoElysium
options:
  deploymentTarget:
    iOS: "$IOS_DEPLOYMENT_TARGET"
  groupSortPosition: top
settings:
  base:
    DEVELOPMENT_TEAM: $TEAM_ID
    CODE_SIGN_STYLE: Automatic
targets:
  DiscoElysium:
    type: application
    platform: iOS
    sources:
      - path: Unity/Classes
      - path: Unity/Libraries
        excludes: ["*.a"]
      - path: Unity/UnityFramework/UnityFramework.h
      - path: Generated
      - path: $ROOT/shell/src
      - path: $ROOT/shell/resources/LaunchScreen.storyboard
      - path: Assets.xcassets
    dependencies:
      - framework: $FW_OUT/GameAssembly.framework
        embed: true
      # 以下由 il2cpp 在运行时 dlopen（见 shell/src/DEBootstrap.mm），只嵌入不链接
      # The following are loaded by il2cpp at runtime with dlopen (see shell/src/DEBootstrap.mm), so they are embedded but not linked
      - { framework: $FW_OUT/AmplifyTextureNative.framework, embed: true, link: false }
      - { framework: $FW_OUT/GLStub.framework, embed: true, link: false }
      - { framework: $FW_OUT/steam_api.framework, embed: true, link: false }
      - { framework: $FW_OUT/GalaxyCSharpGlue.framework, embed: true, link: false }
      - { framework: $FW_OUT/InControlNative.framework, embed: true, link: false }
      - sdk: AVFoundation.framework
      - sdk: AVKit.framework
      - sdk: AudioToolbox.framework
      - sdk: CFNetwork.framework
      - sdk: CoreGraphics.framework
      - sdk: CoreLocation.framework
      - sdk: CoreMedia.framework
      - sdk: CoreText.framework
      - sdk: CoreVideo.framework
      - sdk: Foundation.framework
      - sdk: MediaToolbox.framework
      - sdk: Metal.framework
      - sdk: OpenAL.framework
      - sdk: QuartzCore.framework
      - sdk: Security.framework
      - sdk: SystemConfiguration.framework
      - sdk: UIKit.framework
      - sdk: libiconv.tbd
      - { sdk: CoreMotion.framework, weak: true }
      - { sdk: GameController.framework, weak: true }
      - { sdk: GameKit.framework, weak: true }
    settings:
      base:
        PRODUCT_NAME: DiscoElysium
        PRODUCT_BUNDLE_IDENTIFIER: $BUNDLE_ID
        INFOPLIST_FILE: $ROOT/shell/resources/Info.plist
        CODE_SIGN_ENTITLEMENTS: $ROOT/shell/resources/DiscoElysium.entitlements
        ASSETCATALOG_COMPILER_APPICON_NAME: AppIcon
        TARGETED_DEVICE_FAMILY: "2"
        SUPPORTS_MACCATALYST: NO
        SUPPORTED_PLATFORMS: iphoneos
        ARCHS: arm64
        ENABLE_BITCODE: NO
        GCC_PREFIX_HEADER: Unity/Classes/Prefix.pch
        GCC_PRECOMPILE_PREFIX_HEADER: YES
        HEADER_SEARCH_PATHS:
          - \$(inherited)
          - \$(SRCROOT)/Unity/Classes
          - \$(SRCROOT)/Unity
          - \$(SRCROOT)/Unity/UnityFramework
          - \$(SRCROOT)/Unity/Libraries
          - \$(SRCROOT)/Generated
          - $ROOT/shell/src
        GCC_PREPROCESSOR_DEFINITIONS:
          - \$(inherited)
          - UNITY_VERSION_VER=${UNITY_VER_PARTS[0]}
          - UNITY_VERSION_MAJ=${UNITY_VER_PARTS[1]}
          - UNITY_VERSION_MIN=$UNITY_VER_MIN
        CLANG_CXX_LANGUAGE_STANDARD: gnu++14
        CLANG_CXX_LIBRARY: libc++
        CLANG_ENABLE_OBJC_ARC: YES
        CLANG_ENABLE_MODULES: YES
        GCC_C_LANGUAGE_STANDARD: gnu11
        GCC_ENABLE_CPP_EXCEPTIONS: NO
        GCC_ENABLE_CPP_RTTI: NO
        GCC_ENABLE_OBJC_EXCEPTIONS: YES
        GCC_WARN_INHIBIT_ALL_WARNINGS: YES
        CLANG_WARN_QUOTED_INCLUDE_IN_FRAMEWORK_HEADER: NO
        ENABLE_USER_SCRIPT_SANDBOXING: NO
        LD_RUNPATH_SEARCH_PATHS: "\$(inherited) @executable_path/Frameworks"
        OTHER_LDFLAGS:
          - \$(inherited)
          - \$(SRCROOT)/Unity/Libraries/libiPhone-lib-il2cpp.a
          - \$(SRCROOT)/Unity/Libraries/baselib.a
          - -weak-lSystem
        DEBUG_INFORMATION_FORMAT: dwarf
        STRIP_INSTALLED_PRODUCT: NO
        COPY_PHASE_STRIP: NO
EOF

log "$(m "运行 XcodeGen" "Running XcodeGen")"
(cd "$XCODE_OUT" && xcodegen generate --quiet)
log "$(m "完成：$XCODE_OUT/DiscoElysium.xcodeproj" "Done: $XCODE_OUT/DiscoElysium.xcodeproj")"
