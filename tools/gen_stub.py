#!/usr/bin/env python3
"""为 iOS 上不存在的平台 SDK（Steam、GOG Galaxy、InControl 原生层、OpenGL）生成桩库源码。

只读取本机 Mac 版二进制里的*符号名*，每个函数都生成为"返回 0"的空实现：
  - SteamAPI_Init / SteamAPI_RestartAppIfNecessary 返回 false → 游戏按"无 Steam"模式运行
  - 指针返回 NULL、计数返回 0
每个桩函数第一次被调用时写一条 os_log，方便在控制台里看游戏实际调了什么。

用法：
  gen_stub.py exports   <Mach-O> <库名> <输出.c> [--overrides 文件.c]
  gen_stub.py undefined <Mach-O> <前缀> <库名> <输出.c>
--overrides 指定的文件里用 `// override: 函数名` 标出手写实现，生成器会跳过这些名字并把文件内容拼进来。

Generate stub library sources for platform SDKs that do not exist on iOS (Steam, GOG Galaxy, the
InControl native layer, OpenGL).

Only the *symbol names* are read from your local Mac binaries; every function becomes an empty
implementation that "returns 0":
  - SteamAPI_Init / SteamAPI_RestartAppIfNecessary return false → the game runs in "no Steam" mode
  - pointers come back as NULL, counts as 0
Each stub writes one os_log message the first time it is called, so the console shows what the game
actually calls.

Usage:
  gen_stub.py exports   <Mach-O> <library name> <output.c> [--overrides file.c]
  gen_stub.py undefined <Mach-O> <prefix> <library name> <output.c>
In the file given with --overrides, hand-written implementations are marked with `// override: <function name>`;
the generator skips those names and includes the file's contents in the output.
"""
import os
import re
import subprocess
import sys


def m(zh, en):
    """按 DE_LANG / 系统语言选择输出语言 | Pick the output language from DE_LANG / the system language"""
    lang = os.environ.get("DE_LANG") or os.environ.get("LC_ALL") or os.environ.get("LANG") or ""
    return zh if lang.startswith("zh") else en


HEADER = """// 由 tools/gen_stub.py 生成，请勿手改。
// Generated by tools/gen_stub.py; do not edit by hand.
#include <os/log.h>
#include <stdint.h>

static os_log_t de_stub_log(void)
{
    static os_log_t log;
    if (!log) log = os_log_create("DEPort", "stub.%(lib)s");
    return log;
}

#define DE_STUB(name)                                                              \\
    __attribute__((visibility("default"))) intptr_t name(void)                    \\
    {                                                                             \\
        static int called;                                                        \\
        if (!called) { called = 1; os_log(de_stub_log(), "%(lib)s stub: " #name); } \\
        return 0;                                                                 \\
    }

"""


def nm(macho, *flags):
    out = subprocess.run(["nm", "-arch", "arm64", *flags, macho],
                         capture_output=True, text=True, check=True).stdout
    return out.splitlines()


def c_name(sym):
    # Mach-O C 符号带前导下划线；跳过 C++ 符号和不能作为 C 标识符的名字
    # Mach-O C symbols carry a leading underscore; skip C++ symbols and names that are not valid C identifiers
    if not sym.startswith("_") or sym.startswith("__Z"):
        return None
    name = sym[1:]
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else None


def exported_functions(macho):
    names = []
    for line in nm(macho, "-gU"):
        parts = line.split()
        if len(parts) == 3 and parts[1] == "T":
            n = c_name(parts[2])
            if n:
                names.append(n)
    return names


def undefined_with_prefix(macho, prefix):
    names = []
    for line in nm(macho, "-u"):
        n = c_name(line.strip())
        if n and n.startswith(prefix):
            names.append(n)
    return names


def main():
    args = sys.argv[1:]
    overrides_path = None
    if "--overrides" in args:
        i = args.index("--overrides")
        overrides_path = args[i + 1]
        del args[i:i + 2]

    mode = args[0]
    if mode == "exports":
        macho, lib, out = args[1:4]
        names = exported_functions(macho)
    elif mode == "undefined":
        macho, prefix, lib, out = args[1:5]
        names = undefined_with_prefix(macho, prefix)
    else:
        sys.exit(__doc__)

    override_src = ""
    overridden = set()
    if overrides_path:
        override_src = open(overrides_path).read()
        overridden = set(re.findall(r"//\s*override:\s*(\w+)", override_src))

    names = sorted(set(names) - overridden)
    with open(out, "w") as f:
        f.write(HEADER % {"lib": lib})
        if override_src:
            f.write("// ---- 手写实现：%(file)s ----\n"
                    "// ---- Hand-written implementations: %(file)s ----\n"
                    % {"file": overrides_path.split("/")[-1]})
            f.write(override_src)
            f.write("\n// ---- 自动生成的空实现 ----\n"
                    "// ---- Auto-generated empty implementations ----\n")
        for n in names:
            f.write("DE_STUB(%s)\n" % n)
    print(m("%s: %d 个空实现, %d 个手写实现 → %s", "%s: %d empty stubs, %d hand-written implementations → %s")
          % (lib, len(names), len(overridden), out))


if __name__ == "__main__":
    main()
