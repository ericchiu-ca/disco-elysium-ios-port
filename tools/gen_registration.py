#!/usr/bin/env python3
"""生成 Unity iOS 播放器启动时需要的注册入口（相当于编辑器在关闭 Strip Engine Code 时生成的文件）。

正常构建里 Unity 编辑器会生成 UnityClassRegistration.cpp / UnityICallRegistration.cpp。
这里从 libiPhone-lib-il2cpp.a 的符号表里找出：
  - 全部引擎模块 RegisterModule_XXX（模块与原生类）
  - 全部 icall 注册函数 Register_UnityEngine_*（C++ 修饰名 __Z<长度>Register_...v），
    即托管代码调用的引擎原生方法；编辑器只为游戏用到的那部分生成调用，这里全部注册

用法：gen_registration.py <libiPhone-lib-il2cpp.a> <输出 .cpp>

Generate the registration entry points the Unity iOS player needs at startup (equivalent to the
files the editor generates when Strip Engine Code is disabled).

In a normal build the Unity editor generates UnityClassRegistration.cpp / UnityICallRegistration.cpp.
Here we find, in the symbol table of libiPhone-lib-il2cpp.a:
  - every engine module RegisterModule_XXX (modules and native classes)
  - every icall registration function Register_UnityEngine_* (C++ mangled name __Z<length>Register_...v),
    i.e. the native engine methods called from managed code; the editor only generates calls for
    the ones the game uses, here all of them are registered

Usage: gen_registration.py <libiPhone-lib-il2cpp.a> <output .cpp>
"""
import os
import re
import subprocess
import sys


# 名字不用 m：main() 里的局部变量 m 会遮住它
# Not named m: the local variable m in main() would shadow it
def msg(zh, en):
    """按 DE_LANG / 系统语言选择输出语言 | Pick the output language from DE_LANG / the system language"""
    lang = os.environ.get("DE_LANG") or os.environ.get("LC_ALL") or os.environ.get("LANG") or ""
    return zh if lang.startswith("zh") else en


ICALL_REG = re.compile(r"^__Z\d+(Register_(?:UnityEngine|UnityEngineInternal|Unity)_\w+)v$")

# 编辑器生成的代码总是先注册这两个模块
# Editor-generated code always registers these two modules first
FIRST = ["SharedInternals", "Core"]


def defined_text_symbols(lib):
    out = subprocess.run(["nm", "-arch", "arm64", "-g", "--defined-only", lib],
                         capture_output=True, text=True, check=True).stdout
    syms = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[1] == "T":
            syms.add(parts[2])
    return syms


def main():
    lib, out_path = sys.argv[1], sys.argv[2]
    syms = defined_text_symbols(lib)
    modules = sorted(s[len("_RegisterModule_"):] for s in syms if s.startswith("_RegisterModule_"))
    if not modules:
        sys.exit(msg("在 %s 中没有找到 RegisterModule_* 符号",
                     "No RegisterModule_* symbols found in %s") % lib)
    for required in ("RegisterAllClassesGranular", "RegisterStaticallyLinkedModuleClasses"):
        if not any(s.startswith("__Z") and required + "v" in s for s in syms):
            sys.exit(msg("播放器库缺少 %s，Unity 版本可能不对",
                         "The player library is missing %s; the Unity version may be wrong") % required)
    ordered = [m for m in FIRST if m in modules] + [m for m in modules if m not in FIRST]
    icalls = sorted(m.group(1) for m in map(ICALL_REG.match, syms) if m)
    if not icalls:
        sys.exit(msg("在 %s 中没有找到 Register_UnityEngine_* icall 注册函数",
                     "No Register_UnityEngine_* icall registration functions found in %s") % lib)

    lines = [
        "// 由 tools/gen_registration.py 生成，请勿手改。",
        "// Generated by tools/gen_registration.py; do not edit by hand.",
        "// 注册 libiPhone-lib-il2cpp.a 中的全部 %d 个引擎模块（不做引擎代码裁剪）。" % len(ordered),
        "// Registers all %d engine modules in libiPhone-lib-il2cpp.a (no engine code stripping)." % len(ordered),
        "",
        'extern "C" void RegisterStaticallyLinkedModulesGranular()',
        "{",
    ]
    for m in ordered:
        lines.append("    void RegisterModule_%s(); RegisterModule_%s();" % (m, m))
    lines += [
        "}",
        "",
        "void RegisterStaticallyLinkedModuleClasses();",
        "void InvokeRegisterStaticallyLinkedModuleClasses()",
        "{",
        "    RegisterStaticallyLinkedModuleClasses();",
        "}",
        "",
        "void RegisterAllClassesGranular();",
        "void RegisterAllClasses()",
        "{",
        "    RegisterAllClassesGranular();",
        "}",
        "",
    ]
    for name in icalls:
        lines.append("void %s();" % name)
    lines += [
        "",
        '// 本移植的少量 icall 覆盖（shell/src/DEICallOverrides.mm），必须在全部注册之后调用',
        '// The few icall overrides of this port (shell/src/DEICallOverrides.mm); must be called after all registrations',
        'extern "C" void DERegisterICallOverrides();',
        "",
        "void RegisterAllStrippedInternalCalls()",
        "{",
    ]
    for name in icalls:
        lines.append("    %s();" % name)
    lines += [
        "",
        "    DERegisterICallOverrides();",
        "}",
        "",
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(msg("已生成 %s（%d 个模块，%d 个 icall）", "Generated %s (%d modules, %d icalls)")
          % (out_path, len(ordered), len(icalls)))


if __name__ == "__main__":
    main()
